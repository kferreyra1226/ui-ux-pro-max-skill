let mediaCounter = 0;

function media(
  seed: string,
  altText: string,
  role: ProductMedia['role'],
  sortOrder: number,
  tags: string[],
): ProductMedia {
  mediaCounter += 1;
  return {
    id: `med_${String(mediaCounter).padStart(4, '0')}`,
    placeholderSeed: seed,
    url: null,
    altText,
    role,
    status: 'published',
    sortOrder,
    fileName: `${seed}.webp`,
    fileSizeBytes: 180_000 + sortOrder * 24_000,
    width: 1400,
    height: 1750,
    uploadedAt: '2026-08-14T15:12:00-04:00',
    uploadedBy: 'Owner',
    tags,
  };
}

